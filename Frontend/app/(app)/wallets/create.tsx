/**
 * WALLETS / CREATE — generate a new wallet.
 *
 * The backend generates the keypair; the client never does. This screen only
 * chooses the label, the group and the custody role, and then reads back
 * exactly what the backend created.
 *
 * DESIGN.md §3.2 — creation is a security-relevant action, so the role choice
 * is stated in plain language and the result is confirmed before it is left.
 *
 * Data: POST /wallets
 */

import { useState } from 'react';
import { View } from 'react-native';
import { useRouter } from 'expo-router';
import { useMutation, useQueryClient } from '@tanstack/react-query';

import { spacing } from '@/design/tokens';
import { Text } from '@/components/primitives/Text';
import { Button, Card, Chip, Divider, Input, Row, Stack } from '@/components/primitives';
import { PageContainer } from '@/components/chrome/PageContainer';
import { PageHeader, SectionHeader } from '@/components/chrome/PageHeader';
import { usePageMeta } from '@/components/chrome/shell-context';
import { NoticeBanner } from '@/components/feedback/states';
import { AddressDisplay, WalletAvatar } from '@/components/utility';
import { StatusBadge } from '@/components/StatusBadge';
import { api } from '@/api/client';
import { errorMessage } from '@/hooks/useApi';
import { toast } from '@/stores/toast';
import { useWalletContext } from '@/stores/wallet-context';
import { routes } from '@/navigation/config';
import type { WalletCreateRequest } from '@/api/types';

type Role = NonNullable<WalletCreateRequest['role']>;

const ROLES: { key: Role; label: string; blurb: string }[] = [
  {
    key: 'standard',
    label: 'Standard',
    blurb: 'Holds a key and may sign and broadcast, according to its permissions.',
  },
  {
    key: 'watch_only',
    label: 'Watch only',
    blurb: 'Address only. Cannot sign or broadcast anything.',
  },
  {
    key: 'cold',
    label: 'Cold storage',
    blurb: 'Intended for long-term holding. Broadcast and signing are constrained.',
  },
];

export default function CreateWalletScreen() {
  const router = useRouter();
  const queryClient = useQueryClient();
  const select = useWalletContext((s) => s.select);

  usePageMeta({
    title: 'Create wallet',
    subtitle: 'The backend generates and stores the keypair',
    breadcrumbs: [{ label: 'Wallets' }, { label: 'Create' }],
  });

  const [label, setLabel] = useState('');
  const [group, setGroup] = useState('');
  const [role, setRole] = useState<Role>('standard');

  const create = useMutation({
    mutationFn: (body: WalletCreateRequest) => api.wallets.create(body),
    onSuccess: (wallet) => {
      void queryClient.invalidateQueries({ queryKey: ['wallets'] });
      void queryClient.invalidateQueries({ queryKey: ['portfolio', 'summary'] });
      toast.success(`${wallet.label} created`, wallet.address);
      select(wallet.id);
      router.replace(routes.walletDetail(wallet.id) as never);
    },
  });

  const trimmedLabel = label.trim();
  const canSubmit = trimmedLabel.length > 0 && !create.isPending;

  const onSubmit = () => {
    if (!canSubmit) return;
    create.mutate({
      label: trimmedLabel,
      group: group.trim() || null,
      role,
      cold_storage: role === 'cold',
    });
  };

  const created = create.data;

  return (
    <PageContainer>
      <Stack gap={spacing.xxl}>
        <PageHeader
          title="Create wallet"
          subtitle="A new Solana keypair is generated by the backend and encrypted inside the vault."
        />

        <NoticeBanner
          tone="info"
          title="The private key never reaches this screen"
          message="Only the public address is returned by the API. The secret is encrypted at rest and is never transmitted to the client, logged, or exported."
        />

        <Card variant="elevated">
          <Stack gap={spacing.xl}>
            <Input
              label="Label"
              value={label}
              onChangeText={setLabel}
              placeholder="e.g. Primary custody"
              autoCapitalize="words"
              maxLength={64}
              hint="Shown in the wallet list, the selector and every scoped screen."
            />

            <Input
              label="Group"
              value={group}
              onChangeText={setGroup}
              placeholder="Optional"
              autoCapitalize="words"
              maxLength={64}
              hint="Groups are a label only — the backend stores them as free text."
            />

            <View>
              <SectionHeader title="Custody role" />
              <Row gap={spacing.md} wrap style={{ marginTop: spacing.md }}>
                {ROLES.map((option) => (
                  <Chip
                    key={option.key}
                    label={option.label}
                    selected={role === option.key}
                    onPress={() => setRole(option.key)}
                  />
                ))}
              </Row>
              <Text variant="caption" tone="muted" style={styles.roleBlurb}>
                {ROLES.find((option) => option.key === role)?.blurb}
              </Text>
            </View>

            {create.isError ? (
              <NoticeBanner
                tone="warning"
                title="The wallet was not created"
                message={errorMessage(create.error)}
              />
            ) : null}

            <Divider />

            <Row justify="space-between" align="center" gap={spacing.lg}>
              <Text variant="caption" tone="muted" style={styles.footnote}>
                This action is recorded by the backend. It cannot be undone, though the wallet can
                be ignored.
              </Text>
              <Button
                label="Create wallet"
                variant="primary"
                size="lg"
                loading={create.isPending}
                disabled={!canSubmit}
                onPress={onSubmit}
              />
            </Row>
          </Stack>
        </Card>

        {created ? (
          <View>
            <SectionHeader title="Created" />
            <Card variant="success" style={{ marginTop: spacing.md }}>
              <Stack gap={spacing.lg}>
                <Row gap={spacing.lg} align="center">
                  <WalletAvatar address={created.address} label={created.label} size={38} />
                  <View style={styles.flex}>
                    <Text variant="h3" numberOfLines={1}>
                      {created.label}
                    </Text>
                    <Text variant="caption" tone="muted">
                      {created.role.replace(/_/g, ' ')}
                    </Text>
                  </View>
                  <StatusBadge
                    status={created.signing_enabled ? 'signing enabled' : 'signing disabled'}
                    size="sm"
                  />
                </Row>
                <Divider />
                <AddressDisplay value={created.address} kind="wallet address" size="lg" />
                <Button
                  label="Open wallet"
                  variant="secondary"
                  onPress={() => router.replace(routes.walletDetail(created.id) as never)}
                />
              </Stack>
            </Card>
          </View>
        ) : null}
      </Stack>
    </PageContainer>
  );
}

const styles = {
  roleBlurb: { marginTop: spacing.md },
  footnote: { flex: 1 },
  flex: { flex: 1, gap: spacing.xxs },
} as const;